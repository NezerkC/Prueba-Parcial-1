export function formatearPrecioCLP(precio) {
  const num = Number(precio)
  if (num === 0) {
    return '¡GRATIS / FREE!'
  }
  return '$' + num.toLocaleString('es-CL')
}

export function obtenerRutaImagen(producto) {
  if (!producto) return ''
  const archivo =
    typeof producto === 'string'
      ? producto
      : producto.imagen || (producto.codigo ? `${producto.codigo}.jpg` : '')
  if (!archivo) return ''
  if (/^(https?:|data:|\/\/)/i.test(archivo)) return archivo
  return `/assets/img/${archivo}`
}

export function obtenerCatalogoActivo() {
  try {
    const guardados = localStorage.getItem(CLAVE_INVENTARIO_STORAGE)
    if (guardados) {
      const lista = JSON.parse(guardados)
      if (Array.isArray(lista) && lista.length > 0) {
        return lista.map((item) => {
          if (!item.imagen) {
            const maestro = PRODUCTOS_SONIDO_VIVO.find((m) => m.codigo === item.codigo)
            return {
              ...item,
              imagen: maestro?.imagen || `${item.codigo}.jpg`,
            }
          }
          return item
        })
      }
    }
  } catch (error) {
    console.error('Error reading inventory from LocalStorage:', error)
  }
  return PRODUCTOS_SONIDO_VIVO
}

